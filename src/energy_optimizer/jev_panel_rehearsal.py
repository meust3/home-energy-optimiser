"""Disposable Linux Panel/PostgreSQL rehearsal. Never accepts a service URL.

The Docker launcher supplies a fresh database in a network-none namespace.
Only the pinned evaluation app is loaded; its approval and provider seams are
replaced with offline authorization and fixed responses respectively.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import os
import secrets
import sys
from decimal import Decimal
from pathlib import Path
from uuid import UUID

from energy_optimizer.jev_runner import preflight

PANEL_ROOT = Path("/panel")
PANEL_SOURCE_SHA256 = "91fdd298a362ee1d3ce5261759019b2c3d5ecd3542fc0ba5f00c664e08361914"
ORIGIN = "http://127.0.0.1:18787"
ROUTE = "/v1/evaluation/energy-review-jev"
GRANT = {
    "caller": "application_backend",
    "environment": "test",
    "scopes": ["evaluations:energy-jev"],
    "features": ["diagnostic"],
}


def isolated_environment() -> str:
    """Fail before imports or database access outside the disposable namespace."""
    owner = os.environ.get("JEV_REHEARSAL_OWNER", "")
    if (
        sys.platform != "linux"
        or str(UUID(owner)) != owner
        or {p.name for p in Path("/sys/class/net").iterdir()} != {"lo"}
        or any(
            name in os.environ
            for name in (
                "DATABASE_URL",
                "HA_TOKEN",
                "SUPERVISOR_TOKEN",
                "ENERGY_JEV_APPROVAL_FILE",
                "ENERGY_JEV_MANIFEST_FILE",
            )
        )
    ):
        raise ValueError("Exclusive offline namespace required")
    return owner


def checked_panel_source() -> str:
    digest = hashlib.sha256()
    for path in sorted(PANEL_ROOT.rglob("*")):
        if path.suffix in {".py", ".sql"}:
            digest.update(path.relative_to(PANEL_ROOT).as_posix().encode() + b"\0")
            digest.update(path.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    if digest.hexdigest() != PANEL_SOURCE_SHA256:
        raise ValueError("Pinned Panel source required")
    return digest.hexdigest()


class PanelSession:
    """Own one evaluation child and its temporary grant in a fresh fixture DB."""

    def __init__(self, directory: Path, *, fail_provider: bool = False):
        self.directory = directory
        self.fail_provider = fail_provider
        self.connection = None
        self.key = secrets.token_hex(32)
        self.key_id = secrets.token_hex(16)

    def validate(self, manifest_bytes: bytes, approval_bytes: bytes) -> None:
        self.owner = isolated_environment()
        checked_panel_source()
        self.manifest, self.digest, _ = preflight(manifest_bytes, approval_bytes)
        if self.manifest.transport != "offline_panel_postgres":
            raise ValueError("Panel transport required")
        self.manifest_bytes, self.approval_bytes = manifest_bytes, approval_bytes

    async def start(self, owner):
        import psycopg
        from cryptography.fernet import Fernet
        from psycopg.rows import dict_row

        # The role name is generated by the launcher for this new database.
        role = "jev_" + UUID(self.owner).hex
        url = f"postgresql://{role}@127.0.0.1:5432/ai_control_panel_test"
        self.connection = psycopg.connect(
            url,
            autocommit=True,
            row_factory=dict_row,
            connect_timeout=2,
            options="-c statement_timeout=2000 -c lock_timeout=1500",
        )
        if self.connection.execute(
            "SELECT count(*) n FROM information_schema.tables "
            "WHERE table_schema='public'"
        ).fetchone()["n"]:
            self.connection.close()
            self.connection = None
            raise ValueError("Fresh empty database required; no reset or resume")
        self.directory.mkdir(parents=True, exist_ok=False)
        control = self.directory / "control.json"
        control.write_text(
            json.dumps(
                {
                    "manifest": self.manifest_bytes.decode(),
                    "approval": self.approval_bytes.decode(),
                    "key": self.key,
                    "key_id": self.key_id,
                    "encryption_key": Fernet.generate_key().decode(),
                    "fail_provider": self.fail_provider,
                }
            )
        )
        control.chmod(0o600)
        # No inherited credentials, proxy settings, dotenv, or live approval.
        environment = {
            "PATH": os.defpath,
            "PYTHONPATH": os.pathsep.join(
                [
                    str(Path(__file__).resolve().parents[1]),
                    "/panel/apps",
                    "/panel",
                ]
            ),
            "JEV_REHEARSAL_OWNER": self.owner,
        }
        spawn = asyncio.create_task(
            asyncio.create_subprocess_exec(
                sys.executable,
                "-m",
                __name__,
                str(control),
                env=environment,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.DEVNULL,
            )
        )
        try:
            owner.process = await asyncio.shield(spawn)
        except asyncio.CancelledError:
            owner.process = await spawn
            raise
        self.process = owner.process
        if await self.process.stdout.readline() != b"OFFLINE_PANEL_READY\n":
            raise ValueError("Owned Panel failed startup")
        if self.connection.execute(
            "SELECT pg_try_advisory_lock(771949) owned"
        ).fetchone()["owned"]:
            self.connection.execute("SELECT pg_advisory_unlock(771949)")
            raise ValueError("Panel exclusive ownership lock missing")
        return self.process

    async def exchange(self, request: dict) -> dict:
        from panel_client import AsyncPanelClient

        from energy_optimizer.ai_integration import AISettings
        from energy_optimizer.ai_panel import EnergyPanelAdapter

        async def factory(_settings):
            return AsyncPanelClient(ORIGIN, self.key)

        adapter = EnergyPanelAdapter(
            AISettings(
                enabled=True,
                environment="test",
                base_url=ORIGIN,
                key_file=Path("runtime-test.key"),
            ),
            client_factory=factory,
        )
        receipt = await adapter.review_jev_evaluation_case(
            request["case_id"],
            UUID(request["operation_id"]),
            experiment_id=UUID(request["experiment_id"]),
            manifest_sha256=request["manifest_sha256"],
        )
        return {
            **request,
            **{
                k: receipt[k]
                for k in (
                    "status",
                    "event_id",
                    "request_id",
                    "raw_typed_answer",
                    "reported_usage",
                )
            },
            "execution": "offline_simulation",
        }

    async def finish(self, report: dict) -> None:
        import httpx

        report.update(
            panel_source_sha256=PANEL_SOURCE_SHA256,
            provider_responses="fixed_mock",
            panel_ledger_reconciled=False,
            panel_grant_revoked=False,
            panel_revocation_enforced=False,
        )
        if self.connection is None:
            return
        try:
            c = self.connection
            body = None
            if report["results"]:
                body = {
                    k: report["results"][0][k]
                    for k in (
                        "case_id",
                        "operation_id",
                        "experiment_id",
                        "manifest_sha256",
                    )
                }
                body.update(task_version="1.1.0", adapter_version="1.0.0")
                try:
                    async with httpx.AsyncClient(trust_env=False, timeout=2) as client:
                        duplicate = await client.post(
                            ORIGIN + ROUTE,
                            json=body,
                            headers={"Authorization": "Bearer " + self.key},
                        )
                    report["panel_duplicate_refused"] = duplicate.status_code == 409
                except (httpx.HTTPError, TimeoutError):
                    # HTTP evidence failure must not skip database revocation.
                    report["panel_duplicate_refused"] = False
            c.execute("UPDATE api_keys SET revoked=true WHERE id=%s", (self.key_id,))
            row = c.execute(
                "SELECT revoked FROM api_keys WHERE id=%s", (self.key_id,)
            ).fetchone()
            report["panel_grant_revoked"] = bool(row and row["revoked"])
            rows = c.execute(
                "SELECT e.*,r.status request_status,r.reservation,r.cost "
                "FROM energy_evaluation_attempts e LEFT JOIN requests r "
                "ON r.id=e.data->>'request_id' ORDER BY e.ordinal"
            ).fetchall()
            report["panel_attempt_count"] = len(rows)
            report["panel_reserved_usd"] = str(sum(r["reservation"] or 0 for r in rows))
            matched = len(rows) == len(report["results"])
            matched &= c.execute("SELECT count(*) n FROM requests").fetchone()[
                "n"
            ] == len(rows)
            report["panel_schema_versions"] = [
                r["version"]
                for r in c.execute(
                    "SELECT version FROM schema_version ORDER BY version"
                ).fetchall()
            ]
            report["panel_ledger"] = [
                {
                    **{
                        k: r[k]
                        for k in (
                            "id",
                            "operation_id",
                            "case_id",
                            "ordinal",
                            "status",
                            "request_status",
                        )
                    },
                    "request_id": r["data"].get("request_id"),
                    "reservation_usd": str(r["reservation"]),
                    "actual_cost_usd": None,
                }
                for r in rows
            ]
            for actual, expected in zip(rows, report["results"], strict=False):
                matched &= all(
                    actual[k] == expected[k]
                    for k in (
                        "case_id",
                        "operation_id",
                        "experiment_id",
                    )
                )
                matched &= (
                    actual["cost"] is None
                    and actual["reservation"] == Decimal(expected["reservation_usd"])
                    and actual["request_status"] == "incomplete"
                    and actual["data"]["manifest_sha256"] == expected["manifest_sha256"]
                    and actual["data"].get("reported_usage") is None
                )
                if expected["status"] == "completed":
                    matched &= (
                        actual["status"] == "completed"
                        and actual["id"] == expected["event_id"]
                        and actual["data"]["request_id"] == expected["request_id"]
                        and actual["data"]["raw_typed_answer"]
                        == expected["raw_typed_answer"]
                    )
                else:
                    matched &= actual["status"] != "completed"
            report["panel_ledger_reconciled"] = bool(matched)
            if body is not None:
                async with httpx.AsyncClient(trust_env=False, timeout=2) as client:
                    response = await client.post(
                        ORIGIN + ROUTE,
                        json=body,
                        headers={"Authorization": "Bearer " + self.key},
                    )
                report["panel_revocation_enforced"] = response.status_code == 403
            if not all(
                report[k]
                for k in (
                    "panel_ledger_reconciled",
                    "panel_grant_revoked",
                    "panel_revocation_enforced",
                    "panel_duplicate_refused",
                )
            ):
                report["cleanup_failure"] = "panel_verification_failed"
        finally:
            self.connection.close()
            control = self.directory / "control.json"
            if control.exists():
                control.unlink()


def child(control: Path) -> None:
    """Entrypoint only for the owned child, before any Panel imports."""
    owner = isolated_environment()
    checked_panel_source()
    value = json.loads(control.read_bytes())
    manifest, digest, _ = preflight(
        value["manifest"].encode(), value["approval"].encode()
    )
    os.environ.update(
        DATABASE_URL=f"postgresql://jev_{UUID(owner).hex}@127.0.0.1:5432/ai_control_panel_test",
        ENCRYPTION_KEY=value["encryption_key"],
        PANEL_ENERGY_EVALUATION="1",
    )
    from contextlib import asynccontextmanager

    import panel_energy_challenger as protocol
    import uvicorn
    from api import db
    from api import energy_challenger as endpoint
    from api.energy_challenger_app import app, lifespan
    from api.security import cipher
    from psycopg.types.json import Jsonb

    def offline_approval():
        return {
            "manifest_sha256": digest,
            "max_cost": manifest.max_cost_usd,
        }, manifest.model_dump()

    async def provider_mock(state, questions, key, remaining):
        if key != "offline-fixture-no-provider-credential":
            raise ValueError("Only the fixture credential is accepted")
        if value["fail_provider"]:
            raise TimeoutError()
        return protocol.typed_result(
            {
                "model": "jev-1.13.0",
                "answers": {
                    "review": {
                        "type": "choice",
                        "choice": "needs_review",
                        "probabilities": {
                            "supported": 0.0,
                            "needs_review": 1.0,
                            "insufficient_evidence": 0.0,
                        },
                    }
                },
            }
        )

    endpoint.approval = offline_approval
    endpoint.provider_call = provider_mock

    @asynccontextmanager
    async def fixture_lifespan(application):
        async with lifespan(application):
            policy = {
                "allowed_models": ["system-one-jev"],
                "cloud_allowed": True,
                "daily_budget": "1",
                "monthly_budget": "1",
                "features": ["diagnostic"],
                "max_output_tokens": 1,
                "concurrency": 1,
                "daily_token_limit": 4000000,
                "monthly_token_limit": 4000000,
            }
            db.query(
                "INSERT INTO applications(id,name,policy) "
                "VALUES('home-energy','Offline Energy',%s)",
                (Jsonb(policy),),
            )
            db.query(
                "UPDATE settings SET data=data || %s WHERE id=1",
                (Jsonb({"global_daily_budget": "1", "global_monthly_budget": "1"}),),
            )
            db.query("UPDATE models SET enabled=true WHERE alias='system-one-jev'")
            db.query(
                "INSERT INTO providers(id,encrypted_key) VALUES('typesafe',%s)",
                (cipher().encrypt(b"offline-fixture-no-provider-credential").decode(),),
            )
            db.query(
                "INSERT INTO api_keys(id,app_id,name,hash,grant_data) "
                "VALUES(%s,'home-energy','offline fixture',%s,%s)",
                (
                    value["key_id"],
                    hashlib.sha256(value["key"].encode()).hexdigest(),
                    Jsonb(GRANT),
                ),
            )
            yield

    app.router.lifespan_context = fixture_lifespan

    class OwnedServer(uvicorn.Server):
        async def startup(self, sockets=None):
            await super().startup(sockets)
            if self.started:
                print("OFFLINE_PANEL_READY", flush=True)

    OwnedServer(
        uvicorn.Config(
            app, host="127.0.0.1", port=18787, access_log=False, log_level="critical"
        )
    ).run()


if __name__ == "__main__":
    child(Path(sys.argv[1]))
